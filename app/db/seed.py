def seed_orders() -> int:
    """
    向 orders 表灌入模拟订单数据。
    
    幂等性保障：
    使用 INSERT OR IGNORE 语句配合 order_id 主键约束。
    如果记录已存在，SQLite 会自动忽略并跳过插入，既不会报错也不会产生冗余重复记录。
    
    Returns:
        int: 本次实际新增插入的记录条数。
    """
    # 确保运行种子脚本前数据表已就绪
    init_db()

    insert_sql = """
    INSERT OR IGNORE INTO orders (
        order_id, user_name, product_name, amount, status, tracking_no, created_at
    ) VALUES (?, ?, ?, ?, ?, ?, ?);
    """

    with get_db_connection() as conn:
        cursor = conn.cursor()
        cursor.executemany(insert_sql, MOCK_ORDERS)
        conn.commit()
        inserted_count = cursor.rowcount

    logger.info("Mock 数据填充完成！本次写入 %d 条新记录（若为 0 说明已存在，幂等生效）。", inserted_count)
    return inserted_count


